export type AnchoPapel = 58 | 80;

type Escala = { puntos: number; sx: number; sy: number; alto: number };

/** 32 columnas en ambos anchos: 58 mm = 384 puntos, 80 mm = 576 puntos. */
const ESCALAS: Record<AnchoPapel, Escala> = {
  58: { puntos: 384, sx: 2, sy: 3, alto: 28 },
  80: { puntos: 576, sx: 3, sy: 4, alto: 36 },
};

/** Dibuja una línea de texto como franja de bits (1 = punto negro). */
export function renderLinea(texto: string, ancho: AnchoPapel): Uint8Array {
  const { puntos, sx, sy, alto } = ESCALAS[ancho];
  const bytesFila = puntos / 8;
  const celda = 6 * sx;
  const columnas = Math.floor(puntos / celda);
  const banda = new Uint8Array(bytesFila * alto);
  const margenSup = Math.floor((alto - 7 * sy) / 2);

  for (let c = 0; c < Math.min(texto.length, columnas); c++) {
    const code = texto.charCodeAt(c);
    if (code < 0x21 || code > 0x7e) continue;
    const base = (code - 0x20) * 5;
    for (let gx = 0; gx < 5; gx++) {
      const col = FONT_5X7[base + gx] ?? 0;
      if (!col) continue;
      for (let gy = 0; gy < 7; gy++) {
        if (!((col >> gy) & 1)) continue;
        const x0 = c * celda + gx * sx;
        const y0 = margenSup + gy * sy;
        for (let y = y0; y < y0 + sy; y++) {
          for (let x = x0; x < x0 + sx; x++) {
            banda[y * bytesFila + (x >> 3)] |= 0x80 >> (x & 7);
          }
        }
      }
    }
  }
  return banda;
}

function partirLineas(texto: string, columnas: number): string[] {
  const out: string[] = [];
  for (const raw of texto.replace(/\r/g, "").replace(/\t/g, " ").split("\n")) {
    if (!raw.length) {
      out.push("");
      continue;
    }
    for (let i = 0; i < raw.length; i += columnas) {
      out.push(raw.slice(i, i + columnas));
    }
  }
  return out;
}

/**
 * Comandos ESC/POS en bloques (uno por línea de texto) para enviarlos con
 * pausas: varias portátiles pierden datos si reciben todo el raster de golpe.
 */
export function buildRasterEscPosChunks(
  textoTermico: string,
  opts: { ancho: AnchoPapel; cut?: boolean },
): Uint8Array[] {
  const { puntos, sx, alto } = ESCALAS[opts.ancho];
  const bytesFila = puntos / 8;
  const columnas = Math.floor(puntos / (6 * sx));
  const chunks: Uint8Array[] = [Uint8Array.from([0x1b, 0x40])];

  for (const linea of partirLineas(textoTermico, columnas)) {
    const banda = renderLinea(linea, opts.ancho);
    const cmd = new Uint8Array(8 + banda.length);
    cmd.set([
      0x1d, 0x76, 0x30, 0x00,
      bytesFila & 0xff, bytesFila >> 8,
      alto & 0xff, alto >> 8,
    ]);
    cmd.set(banda, 8);
    chunks.push(cmd);
  }

  const cierre = [0x1b, 0x64, 0x04];
  if (opts.cut !== false) cierre.push(0x1d, 0x56, 0x00);
  chunks.push(Uint8Array.from(cierre));
  return chunks;
}
